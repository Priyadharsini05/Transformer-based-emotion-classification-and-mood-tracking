import pandas as pd
import torch
from transformers import AutoTokenizer, AutoModelForSequenceClassification, pipeline
from sklearn.metrics import classification_report, confusion_matrix
import matplotlib.pyplot as plt
import seaborn as sns
import os
import datetime
from tqdm import tqdm

def load_emotion_file(path):
    data = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            if ";" in line:
                text, label = line.strip().split(";", 1)
                data.append((text.strip(), label.strip()))
    return pd.DataFrame(data, columns=["text", "label"])

df = load_emotion_file("train.txt")  # Make sure this file is in your folder
print(f"Total entries: {len(df)}")
print(df.head())

model_name = "j-hartmann/emotion-english-distilroberta-base"  # faster than BERT
tokenizer = AutoTokenizer.from_pretrained(model_name)
model = AutoModelForSequenceClassification.from_pretrained(model_name)

# Use GPU if available
device = 0 if torch.cuda.is_available() else -1
emotion_classifier = pipeline("text-classification", model=model, tokenizer=tokenizer, device=device)

def batch_predict(texts, batch_size=32):
    preds, confs = [], []
    for i in tqdm(range(0, len(texts), batch_size)):
        batch = texts[i:i+batch_size]
        results = emotion_classifier(batch)
        for r in results:
            preds.append(r['label'])
            confs.append(round(r['score'], 3))
    return preds, confs

cache_file = "predicted_emotions.csv"

if os.path.exists(cache_file):
    df = pd.read_csv(cache_file)
    print("✅ Loaded cached predictions.")
else:
    df['predicted'], df['confidence'] = batch_predict(df['text'].tolist())
    df.to_csv(cache_file, index=False)
    print("✅ Predictions completed and cached.")

print("\n📊 Classification Report:")
print(classification_report(df['label'], df['predicted']))

labels = df['label'].unique()
cm = confusion_matrix(df['label'], df['predicted'], labels=labels)

plt.figure(figsize=(10, 6))
sns.heatmap(cm, annot=True, fmt='d', cmap='YlGnBu', xticklabels=labels, yticklabels=labels)
plt.xlabel("Predicted")
plt.ylabel("Actual")
plt.title("Confusion Matrix")
plt.tight_layout()
plt.show()

def log_mood_entry(journal_text, log_file="mood_log.csv"):
    result = emotion_classifier(journal_text)[0]
    mood = result['label']
    confidence = round(result['score'], 3)
    today = datetime.date.today().isoformat()

    new_entry = {
        "date": today,
        "journal": journal_text,
        "predicted_mood": mood,
        "confidence": confidence
    }

    if os.path.exists(log_file):
        df_log = pd.read_csv(log_file)
        df_log = pd.concat([df_log, pd.DataFrame([new_entry])], ignore_index=True)
    else:
        df_log = pd.DataFrame([new_entry])

    df_log.to_csv(log_file, index=False)
    print(f"✅ Logged: {today} | Mood: {mood} | Confidence: {confidence}")

journal_text = input("📝 How was your day?\n")
log_mood_entry(journal_text)

def plot_mood_trends(log_file="mood_log.csv"):
    if not os.path.exists(log_file):
        print("❌ No mood logs yet.")
        return

    df_log = pd.read_csv(log_file)
    plt.figure(figsize=(10, 5))
    sns.countplot(data=df_log, x="predicted_mood", order=df_log["predicted_mood"].value_counts().index, palette="Set2")
    plt.title("🧠 Mood Frequency Over Time")
    plt.xticks(rotation=45)
    plt.tight_layout()
    plt.show()

plot_mood_trends()







